<?php

it('accepts a bare base64 256-bit key as generated by Render', function () {
    $raw = base64_encode(random_bytes(32));
    putenv("APP_KEY={$raw}");
    $_ENV['APP_KEY'] = $_SERVER['APP_KEY'] = $raw;
    $config = require base_path('config/app.php');
    expect($config['key'])->toBe('base64:'.$raw);
});

it('keeps a Laravel-format key unchanged', function () {
    $key = 'base64:'.base64_encode(random_bytes(32));
    putenv("APP_KEY={$key}");
    $_ENV['APP_KEY'] = $_SERVER['APP_KEY'] = $key;
    $config = require base_path('config/app.php');
    expect($config['key'])->toBe($key);
});
